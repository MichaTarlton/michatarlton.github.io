#!/usr/bin/env bash
# Compile every local component plugin (components-local/<name>/src/index.ts
# → components-local/<name>/dist/components/index.js). Run by `npm run build:components`
# (also wired into prebuild).
set -euo pipefail

# Browser-side mounts compiled to standalone IIFE strings FIRST, so component
# bundles that inline them (landing's afterDOMLoaded) see a current artifact.
if [ -f "components-local/landing/src/simMount.ts" ]; then
  echo "→ building landing sim mount (browser IIFE string)"
  npx esbuild components-local/landing/src/simMount.ts \
    --bundle \
    --format=iife \
    --platform=browser \
    --target=es2020 \
    --minify \
    --outfile="components-local/landing/dist/simMount.generated.js"
  # Wrap as a TS string module so Landing.tsx can inline it as a plain
  # afterDOMLoaded string static (no runtime import of the bundle).
  node -e '
    const fs = require("fs");
    const js = fs.readFileSync("components-local/landing/dist/simMount.generated.js", "utf8");
    const ts = "// Generated by scripts/build-components.sh — do not edit.\n" +
      "// Compiled browser IIFE of components-local/landing/src/simMount.ts,\n" +
      "// inlined into Landing.afterDOMLoaded as a string static.\n" +
      "export default " + JSON.stringify(js) + "\n";
    fs.writeFileSync("components-local/landing/dist/simMount.generated.ts", ts);
  '
fi

for dir in components-local/*/; do
  name="$(basename "$dir")"
  [ -f "$dir/src/index.ts" ] || continue
  echo "→ building local component: $name"
  npx esbuild "$dir/src/index.ts" \
    --bundle \
    --format=esm \
    --platform=node \
    --jsx=automatic \
    --jsx-import-source=preact \
    --packages=external \
    --outfile="$dir/dist/components/index.js"
done